def gui():
    """The bench's screen, 256x256: the 176x166 panel at the top left in the game's own idiom --
    the grey bevelled panel, the grid, the arrow, the result's big frame, the weapon slot with a
    small arrow up to where the chip slot opens, the inventory -- and beside it at (176, 0) the
    chip slot's frame, drawn by the screen only while that slot is open."""
    size, w, h = 256, 176, 166
    px = [[(0, 0, 0, 0) for _ in range(size)] for _ in range(size)]

    def put(x, y, c):
        px[y][x] = (*c, 255)

    panel, light, dark, black, well, edge = (198, 198, 198), (255, 255, 255), (85, 85, 85), (0, 0, 0), (139, 139, 139), (55, 55, 55)
    for y in range(h):
        for x in range(w):
            corner = (x < 3 and y < 3) or (x >= w - 3 and y >= h - 3) or (x < 3 and y >= h - 3) or (x >= w - 3 and y < 3)
            if corner and ((x in (0, w - 1) and y in (0, 1, h - 2, h - 1)) or (y in (0, h - 1) and x in (0, 1, w - 2, w - 1))):
                continue
            if x == 0 or y == 0 or x == w - 1 or y == h - 1:
                put(x, y, black)
            elif x <= 2 or y <= 2:
                put(x, y, light)
            elif x >= w - 3 or y >= h - 3:
                put(x, y, dark)
            else:
                put(x, y, panel)

    def slot(x, y, ox=0, oy=0):
        # An 18x18 sunken square around an item at (x, y): dark top-left edges, light bottom-right.
        for yy in range(y - 1, y + 17):
            for xx in range(x - 1, x + 17):
                if yy == y - 1 or xx == x - 1:
                    put(xx + ox, yy + oy, edge)
                elif yy == y + 16 or xx == x + 16:
                    put(xx + ox, yy + oy, light)
                else:
                    put(xx + ox, yy + oy, well)
        put(x + 16 + ox, y - 1 + oy, panel)
        put(x - 1 + ox, y + 16 + oy, panel)

    def big_slot(x, y):
        # The result's 26x26 frame, the crafting table's: an item at (x, y) sits in its middle.
        x0, y0 = x - 5, y - 5
        for yy in range(y0, y0 + 26):
            for xx in range(x0, x0 + 26):
                if yy == y0 or xx == x0:
                    put(xx, yy, edge)
                elif yy == y0 + 25 or xx == x0 + 25:
                    put(xx, yy, light)
                else:
                    put(xx, yy, well)
        put(x0 + 25, y0, well)
        put(x0, y0 + 25, well)

    def arrow(x, y):
        # The crafting table's arrow, 22 wide and 15 high: a head widening to its tip at the right,
        # a shaft three rows deep.
        for r in range(15):
            head = r + 1 if r <= 7 else 15 - r
            for k in range(head):
                put(x + 14 + k, y + r, well)
        for r, length in ((6, 21), (7, 22), (8, 21)):
            for k in range(length):
                put(x + k, y + r, well)

    for row in range(3):
        for col in range(3):
            slot(GRID_X + 18 * col, GRID_Y + 18 * row)
    arrow(GRID_X + 54 + 5, RESULT_Y)
    big_slot(RESULT_X, RESULT_Y)
    slot(WEAPON_X, WEAPON_Y)
    # A small arrow up from the chip's place to the weapon: the chip goes into it.
    mid = WEAPON_X + 8
    for r in range(4):
        for k in range(-r, r + 1):
            put(mid + k, WEAPON_Y + 19 + r, well)
    for r in range(4, 8):
        put(mid, WEAPON_Y + 19 + r, well)
        put(mid - 1, WEAPON_Y + 19 + r, well)
    for row in range(3):
        for col in range(9):
            slot(8 + 18 * col, 84 + 18 * row)
    for col in range(9):
        slot(8 + 18 * col, 142)
    # The chip slot's frame, kept beside the panel.
    slot(FRAME_U + 1, FRAME_V + 1)
    return px


