def top() -> list[list[Pixel]]:
    """The top: a steel plate in an iron rim, bolted at the corners, scribed with the 3x3 grid."""
    g = Grain(7)
    px: list[list[Pixel]] = []
    for y in range(16):
        row: list[Pixel] = []
        for x in range(16):
            if x in (0, 15) or y in (0, 15):
                c = PALETTE["I"]
            elif x in (1, 14) or y in (1, 14):
                c = PALETTE["i"]
            else:
                c = _shade(PALETTE["S"], int(g.next() * 15) - 9)
            row.append((*c, 255))
        px.append(row)
    # The scribed grid: three cells of three, lines in the plate's shade, a lit edge below each.
    for k in (3, 6, 9, 12):
        for t in range(3, 13):
            px[k][t] = (*PALETTE["D"], 255)
            px[t][k] = (*PALETTE["D"], 255)
    for x, y in ((2, 2), (13, 2), (2, 13), (13, 13)):
        px[y][x] = (*PALETTE["T"], 255)
        if y + 1 < 15 and x + 1 < 15:
            px[y + 1][x + 1] = (*PALETTE["D"], 255)
    return px


def bottom() -> list[list[Pixel]]:
    """The bottom: dark walnut boards in an iron rim."""
    px = _walnut(13)
    for y in range(16):
        for x in range(16):
            px[y][x] = (*_shade(px[y][x][:3], -28), 255)
            if x in (0, 15) or y in (0, 15):
                px[y][x] = (*PALETTE["I"], 255)
    return px


