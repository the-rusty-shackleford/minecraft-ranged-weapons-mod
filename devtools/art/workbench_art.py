def generate(want: set[str]) -> None:
    """requires: run from anywhere; want names textures and/or model.
    effects: writes the bench's and the chip's textures, models and block states. throws: OSError."""
    if "textures" in want:
        faces = {"top": top(), "front": front(), "side": side(), "bottom": bottom()}
        for name, raster in faces.items():
            write_png(ASSETS / f"textures/block/weapons_workbench_{name}.png", 16, 16, raster)
        write_png(ASSETS / "textures/item/lock_on_chip.png", 16, 16, chip_icon())
        write_png(ASSETS / "textures/item/empty_slot_launcher.png", 16, 16, ghost(EMPTY_LAUNCHER))
        write_png(ASSETS / "textures/item/empty_slot_chip.png", 16, 16, ghost(EMPTY_CHIP))
        write_png(ASSETS / "textures/gui/workbench.png", 256, 256, gui())
        print("textures: weapons_workbench_{top,front,side,bottom}.png, lock_on_chip.png, empty_slot_{launcher,chip}.png, gui/workbench.png")
    if "model" in want:
        for path, model in models().items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(model, indent=2) + "\n")
        print("model: weapons_workbench (block, item, state), lock_on_chip")


if __name__ == "__main__":
    generate({"textures", "model"})
