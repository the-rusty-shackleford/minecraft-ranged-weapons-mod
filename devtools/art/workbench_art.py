def write_png(path: Path, width: int, height: int, rows) -> None:
    """rows: rows of (r, g, b, a), top row first."""
    raw = b"".join(b"\x00" + b"".join(bytes(p) for p in row) for row in rows)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"\x89PNG\r\n\x1a\n"
                     + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9))
                     + chunk(b"IEND", b""))


class Grain:
    """A deterministic grain, so flat colours read as material."""

    def __init__(self, seed: int) -> None:
        self.state = seed & 0xFFFFFFFF

    def next(self) -> float:
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state / 0xFFFFFFFF


def _shade(rgb, delta):
    return tuple(max(0, min(255, c + delta)) for c in rgb)


def _grid(rows: list[str]) -> list[list[Pixel]]:
    """effects: a 16 by 16 raster from character rows; '.' is transparent."""
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    return [[(0, 0, 0, 0) if c == "." else (*PALETTE[c], 255) for c in row] for row in rows]


def _over(base: list[list[Pixel]], rows: list[str], x0: int = 0, y0: int = 0) -> None:
    """effects: paints the characters of {@code rows} over {@code base} from (x0, y0); '.' leaves it."""
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c != "." and 0 <= y0 + y < 16 and 0 <= x0 + x < 16:
                base[y0 + y][x0 + x] = (*PALETTE[c], 255)


def _walnut(seed: int) -> list[list[Pixel]]:
    """effects: a walnut panel of horizontal boards, four pixels deep with a seam between, grained."""
    g = Grain(seed)
    px: list[list[Pixel]] = []
    for y in range(16):
        row: list[Pixel] = []
        for x in range(16):
            if y % 4 == 3:
                c = PALETTE["V"]
            else:
                c = PALETTE["W"] if (x + 3 * (y // 4)) % 7 not in (0, 4) else PALETTE["w"]
                c = _shade(c, int(g.next() * 7) - 3)
            row.append((*c, 255))
        px.append(row)
    return px


def _framed(panel: list[list[Pixel]], band: int) -> list[list[Pixel]]:
    """effects: the smithing table's frame round {@code panel}: an iron band {@code band} deep along
    the top, two-pixel posts at the sides, one row at the bottom, darkest at the corners."""
    px = [row[:] for row in panel]
    for y in range(16):
        for x in range(16):
            top = y < band
            post = x < 2 or x > 13
            bottom = y == 15
            if top or post or bottom:
                if (x in (0, 15)) or y == 0 or bottom:
                    c = PALETTE["I"]
                elif top and y == band - 1:
                    c = PALETTE["K"]
                elif x in (1, 14) and not top:
                    c = PALETTE["i"]
                else:
                    c = PALETTE["j"] if y == 1 else PALETTE["i"]
                px[y][x] = (*c, 255)
    for x, y in ((0, 0), (15, 0), (0, 15), (15, 15)):
        px[y][x] = (*PALETTE["K"], 255)
    return px


